//! UniFFI0.32.2 close policy. The upstream automatic AutoCloseable helper
//! collides with a real exported close method (upstream issue2955).
//! Only remove the handle-destruction alias for objects whose extracted Rust
//! metadata declares close; keep the source lifecycle call and destroy intact.
use anyhow::{Result, ensure};

const SHIM: &str = "    @Synchronized\n    override fun close() {\n        this.destroy()\n    }\n";

/// A native string field named `message` is the actual Throwable message.
/// Retain it and every converter field; remove only the conflicting diagnostic
/// getter generated by the pinned upstream template for that exact variant.
pub(super) fn preserve_error_messages(
    source: &str,
    variants: &[(String, String)],
) -> Result<String> {
    let mut output = source.to_owned();
    for (error, variant) in variants {
        let canonical = |name: &str| {
            ensure!(
                name.bytes().all(|v| v.is_ascii_alphanumeric())
                    && name.as_bytes().first().is_some_and(u8::is_ascii_uppercase),
                "unsupported Kotlin error naming"
            );
            Ok::<_, anyhow::Error>(
                name.strip_suffix("Error")
                    .map_or_else(|| name.to_owned(), |v| format!("{v}Exception")),
            )
        };
        let error = canonical(error)?;
        let variant = canonical(variant)?;
        let header = format!("sealed class {error}: kotlin.Exception()");
        ensure!(
            output.matches(&header).count() == 1,
            "unexpected Kotlin error header"
        );
        let start = output.find(&header).expect("counted error");
        let end = output[start..]
            .find("    companion object ErrorHandler")
            .ok_or_else(|| anyhow::anyhow!("unexpected Kotlin error boundary"))?
            + start;
        let declaration = format!("\n    class {variant}(");
        let body = &output[start..end];
        ensure!(
            body.matches(&declaration).count() == 1,
            "unexpected Kotlin error variant"
        );
        let variant_start = body.find(&declaration).expect("counted variant") + start;
        let variant_end = output[variant_start..end]
            .find("\n    }\n")
            .ok_or_else(|| anyhow::anyhow!("unexpected Kotlin variant boundary"))?
            + variant_start;
        let body = &output[variant_start..variant_end];
        let field = "        val `message`: kotlin.String";
        let getter = "        override val message\n            get() = \"";
        ensure!(
            body.matches(field).count() == 1 && body.matches(getter).count() == 1,
            "unexpected Kotlin message field/getter"
        );
        let getter_start = body.find(getter).expect("counted getter");
        let getter_end = body[getter_start..]
            .find('\n')
            .and_then(|first| {
                body[getter_start + first + 1..]
                    .find('\n')
                    .map(|second| getter_start + first + 1 + second + 1)
            })
            .unwrap_or(body.len());
        let removed = &body[getter_start..getter_end];
        ensure!(
            removed.trim_end().ends_with('"') && removed.lines().count() == 2,
            "unexpected Kotlin message getter layout"
        );
        let mut replacement =
            body[..getter_start].replace(field, "        override val `message`: kotlin.String");
        replacement.push_str(&body[getter_end..]);
        output.replace_range(variant_start..variant_end, &replacement);
    }
    Ok(output)
}

pub(super) fn preserve_close(source: &str, methods: &[(String, bool)]) -> Result<String> {
    let mut output = source.to_owned();
    for (name, asynchronous) in methods {
        let header = format!("open class {name}: Disposable, AutoCloseable, {name}Interface");
        ensure!(
            output.matches(&header).count() == 1,
            "unexpected Kotlin object header for {name}"
        );
        let start = output.find(&header).expect("counted header");
        let end = start
            + output[start..]
                .find("    internal inline fun <R> callWithHandle(")
                .ok_or_else(|| anyhow::anyhow!("unexpected Kotlin handle layout for {name}"))?;
        let prefix = &output[start..end];
        ensure!(
            prefix.matches(SHIM).count() == 1,
            "unexpected Kotlin close helper for {name}"
        );
        let method = if *asynchronous {
            "override suspend fun `close`()"
        } else {
            "override fun `close`()"
        };
        // Scope the exported method to this object, rather than another class.
        let tail_end = output[end..]
            .find("\nopen class ")
            .map_or(output.len(), |offset| end + offset);
        ensure!(
            output[end..tail_end].matches(method).count() == 1,
            "missing source close for {name}"
        );
        let replacement = prefix
            .replace(&header, &header.replace(", AutoCloseable", ""))
            .replacen(SHIM, "", 1);
        output.replace_range(start..end, &replacement);
    }
    Ok(output)
}

#[cfg(test)]
mod tests {
    use super::*;
    fn error_source(name: &str, variant: &str) -> String {
        format!(
            "sealed class {name}: kotlin.Exception() {{\n    class {variant}(\n        val `code`: kotlin.String,\n        val `message`: kotlin.String\n    ) : {name}() {{\n        override val message\n            get() = \"code=${{ `code` }}, message=${{ `message` }}\"\n    }}\n    companion object ErrorHandler\n}}\n"
        )
    }
    #[test]
    fn preserves_native_message_field_without_a_conflicting_diagnostic_getter() {
        let metadata = [("Error".to_owned(), "Sdk".to_owned())];
        let untouched = error_source("OtherException", "Sdk");
        let source = format!("{}{untouched}", error_source("Exception", "Sdk"));
        let actual = preserve_error_messages(&source, &metadata).unwrap();
        assert!(actual.starts_with("sealed class Exception"));
        assert!(actual.contains("override val `message`: kotlin.String"));
        assert!(actual.contains("val `code`: kotlin.String"));
        assert_eq!(actual.matches("        override val message\n").count(), 1);
        assert!(actual.ends_with(&untouched));
        assert!(preserve_error_messages(&actual, &metadata).is_err());
        assert!(
            preserve_error_messages(&source.replace("kotlin.String", "kotlin.Int"), &metadata)
                .is_err()
        );
        assert!(
            preserve_error_messages(&source.replace("get() =", "changed ="), &metadata).is_err()
        );
        assert!(
            preserve_error_messages(&source, &[("missing_name".into(), "Sdk".into())]).is_err()
        );
    }
    fn object(name: &str, asynchronous: bool) -> String {
        format!(
            "open class {name}: Disposable, AutoCloseable, {name}Interface\n{{\n    override fun destroy() {{ actualFree() }}\n{SHIM}\n    internal inline fun <R> callWithHandle(block: (Long) -> R): R {{ actualCall() }}\n    override {}fun `close`() {{ actualSourceClose() }}\n}}\n",
            if asynchronous { "suspend " } else { "" }
        )
    }
    #[test]
    fn preserves_actual_sync_and_async_close_and_other_objects() {
        let host = object("Host", false);
        let source = format!(
            "{}{}{}",
            object("NativeClient", true),
            object("Workspace", false),
            host
        );
        let actual = preserve_close(
            &source,
            &[("NativeClient".into(), true), ("Workspace".into(), false)],
        )
        .unwrap();
        assert!(actual.ends_with(&host));
        assert_eq!(actual.matches("actualSourceClose()").count(), 3);
        assert_eq!(actual.matches("actualFree()").count(), 3);
        assert_eq!(actual.matches(SHIM).count(), 1);
        assert!(!actual.contains("NativeClient: Disposable, AutoCloseable"));
        assert!(!actual.contains("Workspace: Disposable, AutoCloseable"));
    }
    #[test]
    fn rejects_drift_missing_source_and_reapplication() {
        let metadata = [("NativeClient".into(), true)];
        let source = object("NativeClient", true);
        assert!(preserve_close(&source.replace(SHIM, ""), &metadata).is_err());
        assert!(
            preserve_close(
                &source.replace("override suspend fun `close`", "fun other"),
                &metadata
            )
            .is_err()
        );
        assert!(preserve_close(&source.replace("callWithHandle", "changed"), &metadata).is_err());
        assert!(preserve_close(&format!("{source}{source}"), &metadata).is_err());
        assert!(preserve_close(&preserve_close(&source, &metadata).unwrap(), &metadata).is_err());
        assert_eq!(preserve_close(&source, &[]).unwrap(), source);
    }
}
