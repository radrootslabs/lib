//! Exact source-owned redistribution material for every derived artifact.
use std::{fs, path::Path};

use serde::Deserialize;
use sha2::{Digest, Sha256};

use crate::{build_control::Mode, sdk_generation::fs::write_or_check};

pub(crate) const CONTRACT: &str = "contracts/codegen/redistribution_materials.v1.json";
pub(crate) const OUTPUT: &str = "crates/domain/NOTICE";
const MATERIALS: [&str; 6] = [
    "crates/domain/data/currency_registry_v1.csv",
    "crates/domain/data/currency_registry_v1.notice",
    "crates/domain/data/currency_registry_v1.license",
    "crates/domain/data/timezone_registry_v1.notice",
    "crates/domain/data/timezone_registry_v1.license",
    "crates/domain/data/timezone_registry_v1.copying",
];

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Contract {
    schema: String,
    output: String,
    max_input_bytes: usize,
    max_output_bytes: usize,
    source_distribution: String,
    materials: Vec<Material>,
}
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Material {
    path: String,
    sha256: String,
}

fn read(root: &Path, name: &str) -> Result<String, String> {
    let path = root.join(name);
    let metadata =
        fs::symlink_metadata(&path).map_err(|_| "redistribution material is missing".to_owned())?;
    if !metadata.is_file() || metadata.len() > 16_384 {
        return Err("redistribution material must be a bounded regular file".to_owned());
    }
    let value =
        fs::read_to_string(path).map_err(|_| "redistribution material must be UTF8".to_owned())?;
    if value.is_empty() || value.len() > 16_384 {
        return Err("redistribution material size is invalid".to_owned());
    }
    Ok(value)
}

/// Render original material verbatim; no timestamp, source path or host state.
pub(crate) fn render(root: &Path) -> Result<String, String> {
    let contract: Contract = serde_json::from_str(&read(root, CONTRACT)?)
        .map_err(|_| "invalid redistribution materials contract".to_owned())?;
    if contract.schema != "radroots.redistribution_materials.v1"
        || contract.output != OUTPUT
        || contract.max_input_bytes != 16_384
        || contract.max_output_bytes != 65_536
        || contract.source_distribution.trim().is_empty()
        || !contract
            .materials
            .iter()
            .map(|v| v.path.as_str())
            .eq(MATERIALS)
    {
        return Err("redistribution material authority drifted".to_owned());
    }
    let mut output = String::from(
        "Radroots data redistribution material v1\n\nGenerated by cargo xtask generate data-notices --write.\nRetain this complete file with derived artifacts.\n\n",
    );
    output.push_str(&contract.source_distribution);
    output.push('\n');
    for material in contract.materials {
        let text = read(root, &material.path)?;
        let digest = format!("{:x}", Sha256::digest(text.as_bytes()));
        if digest != material.sha256 {
            return Err("redistribution material digest mismatch".to_owned());
        }
        use std::fmt::Write as _;
        write!(
            output,
            "\n===== {} / sha256:{} =====\n",
            material.path, digest
        )
        .map_err(|_| "cannot render redistribution material".to_owned())?;
        output.push_str(&text);
        if !text.ends_with('\n') {
            output.push('\n');
        }
    }
    if output.len() > 65_536 {
        return Err("redistribution material output exceeds its bound".to_owned());
    }
    Ok(output)
}

pub(crate) fn run(flag: &str, root: &Path) -> Result<(), String> {
    let mode = match flag {
        "--write" => Mode::Write,
        "--check" => Mode::Check,
        _ => return Err("data-notices requires exactly --write or --check".to_owned()),
    };
    write_or_check(&root.join(OUTPUT), &render(root)?, mode)
}

/// Copy the current complete material, requiring its owning generated source
/// to be fresh. Consumer artifact checks compare bytes, not merely metadata.
pub(crate) fn install(root: &Path, destination: &Path, mode: Mode) -> Result<String, String> {
    let expected = render(root)?;
    write_or_check(&root.join(OUTPUT), &expected, Mode::Check)?;
    write_or_check(destination, &expected, mode)?;
    Ok(format!("{:x}", Sha256::digest(expected.as_bytes())))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn fixture() -> tempfile::TempDir {
        let root = tempfile::tempdir().unwrap();
        for name in [CONTRACT].into_iter().chain(MATERIALS) {
            let destination = root.path().join(name);
            fs::create_dir_all(destination.parent().unwrap()).unwrap();
            fs::copy(crate::workspace_root().join(name), destination).unwrap();
        }
        root
    }

    #[test]
    fn complete_exact_material_round_trips_and_rejects_stale_consumer_bytes() {
        let root = fixture();
        run("--write", root.path()).unwrap();
        let output = fs::read_to_string(root.path().join(OUTPUT)).unwrap();
        for name in MATERIALS {
            assert!(output.contains(&read(root.path(), name).unwrap()));
        }
        run("--check", root.path()).unwrap();
        run("--write", root.path()).unwrap();
        assert_eq!(
            fs::read_to_string(root.path().join(OUTPUT)).unwrap(),
            output
        );
        let consumer = root.path().join("consumer/NOTICE");
        install(root.path(), &consumer, Mode::Write).unwrap();
        install(root.path(), &consumer, Mode::Check).unwrap();
        fs::write(&consumer, "truncated material\n").unwrap();
        assert!(install(root.path(), &consumer, Mode::Check).is_err());
        fs::write(root.path().join(OUTPUT), "stale source\n").unwrap();
        assert!(install(root.path(), &consumer, Mode::Write).is_err());
    }

    #[test]
    fn missing_changed_oversized_and_nonregular_material_never_generates() {
        for name in MATERIALS {
            let root = fixture();
            let path = root.path().join(name);
            fs::remove_file(&path).unwrap();
            assert!(run("--write", root.path()).is_err());
            fs::write(&path, "changed\n").unwrap();
            assert!(run("--write", root.path()).is_err());
            fs::write(&path, vec![b'x'; 16_385]).unwrap();
            assert!(run("--write", root.path()).is_err());
            fs::remove_file(&path).unwrap();
            fs::create_dir(&path).unwrap();
            assert!(run("--write", root.path()).is_err());
            assert!(!root.path().join(OUTPUT).exists());
        }
    }

    #[test]
    fn contract_cannot_select_extra_paths_or_silently_expand_limits() {
        for field in [
            "output",
            "materials",
            "max_input_bytes",
            "max_output_bytes",
            "schema",
            "extra",
        ] {
            let root = fixture();
            let path = root.path().join(CONTRACT);
            let mut value: serde_json::Value =
                serde_json::from_str(&fs::read_to_string(&path).unwrap()).unwrap();
            value[field] = serde_json::json!("unapproved");
            fs::write(&path, serde_json::to_vec(&value).unwrap()).unwrap();
            assert!(run("--write", root.path()).is_err(), "{field}");
        }
        assert!(run("--unknown", fixture().path()).is_err());
    }
}
